#!/usr/bin/env python3
"""Inventory every RMAPI C function in the pinned release's raymath.h."""

import argparse
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
MAPPING = {
    "Vector3Add": "vector3_add", "Vector3Subtract": "vector3_subtract",
    "Vector3Scale": "vector3_scale", "Vector3DotProduct": "vector3_dot",
    "Vector3Length": "vector3_length", "Vector3CrossProduct": "vector3_cross",
    "Vector3Normalize": "vector3_normalize", "Vector3Transform": "vector3_transform",
    "Vector3Lerp": "vector3_lerp", "MatrixIdentity": "matrix_identity",
    "MatrixTranslate": "matrix_translate", "MatrixScale": "matrix_scale",
    "MatrixRotateXYZ": "matrix_rotate_xyz", "MatrixMultiply": "matrix_multiply",
    "MatrixInvert": "matrix_invert", "MatrixPerspective": "matrix_perspective",
    "MatrixOrtho": "matrix_ortho", "MatrixLookAt": "matrix_look_at",
    "QuaternionIdentity": "quaternion_identity", "QuaternionNormalize": "quaternion_normalize",
    "QuaternionMultiply": "quaternion_multiply", "QuaternionSlerp": "quaternion_slerp",
    "QuaternionFromAxisAngle": "quaternion_from_axis_angle", "QuaternionToMatrix": "quaternion_to_matrix",
    "QuaternionFromMatrix": "quaternion_from_matrix",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", type=Path, help="default: raylib's pkg-config includedir/raymath.h")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header = args.header
    if header is None:
        includedir = subprocess.check_output(["pkg-config", "--variable=includedir", "raylib"], text=True).strip()
        header = Path(includedir) / "raymath.h"
    text = header.read_text()
    names = re.findall(r"^RMAPI\s+\w+\s+(\w+)\s*\(", text, re.MULTILINE)
    if not names or len(names) != len(re.findall(r"^RMAPI\s+", text, re.MULTILINE)) or len(names) != len(set(names)):
        sys.exit("unparsed/duplicate RMAPI declaration; update the inventory parser")
    if set(MAPPING) - set(names):
        sys.exit("implemented function is absent from the supplied upstream header")
    goose_functions = set(re.findall(r"^fn\s+(\w+)\s*\(", (ROOT / "raymath.goose").read_text(), re.MULTILINE))
    if goose_functions != set(MAPPING.values()):
        sys.exit("Goose wrapper names and inventory mapping differ")
    adapter = (ROOT / "src/raylib_math.c").read_text()
    tests = (ROOT / "tests/test_raymath_adapter.c").read_text()
    for name in MAPPING:
        if not all(re.search(r"\b" + name + r"\s*\(", source) for source in (adapter, tests)):
            sys.exit(f"{name} has no native implementation/oracle call")
    lines = [
        "# raymath function inventory", "",
        "Generated by `tools/raymath_inventory.py`; do not edit by hand.",
        "Source: raylib 6.2, commit `02566453880e06bec97f5b8160fa6fe1e98397ca`, `src/raymath.h`.",
        f"All {len(names)} RMAPI C functions are listed: {len(MAPPING)} implemented and tested, {len(names) - len(MAPPING)} planned.",
        "C++ operators/macros are not C functions. Types/constants and ABI notes are documented in `API_STATUS.md`.", "",
        "| Upstream function | Module | Goose wrapper | Status |", "|---|---|---|---|",
    ]
    for name in names:
        module = next((prefix for prefix in ("Vector2", "Vector3", "Vector4", "Matrix", "Quaternion") if name.startswith(prefix)), "Scalar")
        wrapper = f"`raymath::{MAPPING[name]}`" if name in MAPPING else "—"
        status = "implemented" if name in MAPPING else "planned"
        lines.append(f"| `{name}` | {module} | {wrapper} | {status} |")
    content = "\n".join(lines) + "\n"
    path = ROOT / "docs/RAYMATH_STATUS.md"
    if args.write:
        path.write_text(content)
    elif not path.exists() or path.read_text() != content:
        sys.exit("raymath inventory is stale: run tools/raymath_inventory.py --write")
    print(f"raymath inventory verified: {len(names)} functions, {len(MAPPING)} implemented")


if __name__ == "__main__":
    main()
